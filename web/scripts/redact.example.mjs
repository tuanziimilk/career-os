/* 脱敏词表的**结构说明**。真实词表在 redact.local.mjs，那个文件不进版本库。
 *
 *     cp web/scripts/redact.example.mjs web/scripts/redact.local.mjs
 *     然后把占位换成真实词条
 *
 * ══════════ 为什么词表要挪出版本控制 ══════════
 *
 * 2026-09-15 仓库公开后核查发现的问题：**产物是干净的，脱敏机制也在正常工作，
 * 但机制本身在公开仓库里，而且它把「真实词 → 替换词」的对照关系完整写了出来。**
 *
 * 读三行代码就能知道前雇主全称、内部系统缩写、内部平台代号，
 * 以及当时在投的目标公司叫什么 —— 后面这条尤其糟，它泄漏的不是历史，是**当下的求职意图**。
 *
 * 这不是写法问题，是结构问题：**正则必须有明文才能匹配**。
 * 把词改写、编码、哈希都会让它失效。唯一的解法是让那份明文不进版本库。
 *
 * ══════════ 什么该进 local、什么留在仓库里 ══════════
 *
 * 判据是「这个词本身会不会指认出某个具体的人/公司/系统」：
 *
 *   进 local（本文件是它的占位版）——
 *     前雇主全称、内部系统名与缩写、内部平台代号、在投目标公司及其产品名、
 *     精确到小数点的内部指标、内部项目文档编号。
 *
 *   留在 leaks.mjs 里（不必藏）——
 *     「短板」「现状自检」「你目前答不出」这类**通用的自评措辞**。
 *     它们暴露的是「我在过滤哪一类表达」，不指认任何具体对象，
 *     而且留在仓库里才能被 eval-leaks.mjs 的断言压住。
 *
 * ══════════ 缺了这个文件会怎样 ══════════
 *
 * **不会静默跳过。** 判据是知识库在不在：
 *   · 知识库在（= 这是作者本人的机器）→ 三个消费方一律**报错退出**
 *   · 知识库不在（= 别人克隆的仓库）→ 打印「身份类断言未执行」并继续，
 *     因为那台机器上本来就没有需要脱敏的原始素材
 *
 * 这个区分是刻意的。`check-line-endings.mjs` 在单仓库合并那天踩过反面案例：
 * 目录找不到就静默返回空，于是闸门**扫了零个文件然后报告全部通过** ——
 * 一道从不报错的闸门比没有闸门更糟，因为它占着「已经检查过了」这个位置。
 */

/** @typedef {{ match: RegExp, replace: string, reason: string, hard?: boolean }} Identifier */

/**
 * 会指认出具体对象的词。**顺序有意义**：先长后短，
 * 否则短的会把长的抢先替换掉（真实词表里踩过：「内容质检平台」抢在「内容质检平台」前面）。
 *
 * - `match`   用于替换，必须带 /g
 * - `replace` 换成什么。选一个**看得出被脱敏过**的词，
 *             比如 `XX%` 比删掉整句好 —— 删掉会让人以为原文就没有数字
 * - `reason`  为什么它算敏感。写清楚，将来有人觉得是误判时能照着判断
 * - `hard`    true = 连图源那种「只查最硬的几个词」的场景也要查
 *
 * @type {Identifier[]}
 */
export const IDENTIFIERS = [
  {
    match: /示例公司全称有限公司/g,
    replace: "某行业平台",
    reason: "前雇主全称。这是最硬的一条",
    hard: true,
  },
  {
    match: /\bDEMOSYS\b/g,
    replace: "内部后台系统",
    reason: "内部系统缩写。三个大写字母那种，正文里很扎眼",
    hard: true,
  },
  {
    match: /Demo[- ]?AI[- ]?Center/gi,
    replace: "内部 AI 数据平台",
    reason: "内部平台代号",
    hard: true,
  },
  {
    match: /DemoTarget/gi,
    replace: "某目标公司",
    reason: "在投的目标公司名。泄漏的是当下的求职意图，不是历史",
  },
  {
    match: /DemoProduct/gi,
    replace: "某目标公司产品",
    reason: "目标公司的产品名。同上",
  },
  {
    match: /XY\s?(内容)?示例平台|XY\s?平台/g,
    replace: "内容质检平台",
    reason: "「两个大写字母代号 + 中文产品名」是内部系统命名的典型形态",
  },
  {
    match: /示例基础库/g,
    replace: "内部主数据库",
    reason: "「XX基础库」是内部系统常见命名",
  },
  {
    match: /12\.3\s?%/g,
    replace: "XX%",
    reason: "精确到小数点后一位的内部基线指标。配上上下文足够让知情的人对上号",
  },
];
